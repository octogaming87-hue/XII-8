-- Jalankan seluruh SQL ini di Supabase > SQL Editor.
-- Buat akun guru lebih dahulu melalui Authentication > Users.
create table if not exists public.admins (
  user_id uuid primary key references auth.users(id) on delete cascade
);
create table if not exists public.students (
  id bigint generated by default as identity primary key,
  number integer unique not null,
  name text not null,
  created_at timestamptz default now()
);
create table if not exists public.announcements (
  id bigint generated by default as identity primary key,
  title text not null, body text not null, created_at timestamptz default now()
);
create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  title text not null, description text, deadline text, created_at timestamptz default now()
);
create table if not exists public.schedule (
  id bigint generated by default as identity primary key,
  day text, subject text not null, time text, teacher text, created_at timestamptz default now()
);
create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id text, status text, date date, created_at timestamptz default now()
);
create table if not exists public.gallery (
  id bigint generated by default as identity primary key,
  title text not null, url text, created_at timestamptz default now()
);
create table if not exists public.fund (
  id bigint generated by default as identity primary key,
  date text, note text, kind text, amount numeric default 0, created_at timestamptz default now()
);
create table if not exists public.aspirations (
  id bigint generated by default as identity primary key,
  sender text, body text not null, created_at timestamptz default now()
);
insert into public.students(number,name)
select n, 'Siswa ' || lpad(n::text,2,'0') from generate_series(1,36) n
on conflict (number) do nothing;

-- Daftarkan UUID user guru di tabel admins setelah membuat akun.
-- Contoh: insert into public.admins(user_id) values ('UUID-DARI-AUTH-USERS');

alter table public.admins enable row level security;
alter table public.students enable row level security;
alter table public.announcements enable row level security;
alter table public.tasks enable row level security;
alter table public.schedule enable row level security;
alter table public.attendance enable row level security;
alter table public.gallery enable row level security;
alter table public.fund enable row level security;
alter table public.aspirations enable row level security;

create or replace function public.is_xi8_admin()
returns boolean language sql stable security definer set search_path=public
as $$ select exists(select 1 from public.admins where user_id=auth.uid()) $$;

-- Admin list hanya dapat dilihat oleh pemilik akun sendiri.
create policy "admin reads own record" on public.admins for select to authenticated using (user_id=auth.uid());
-- Data kelas dapat dibaca publik. Hanya admin yang boleh mengubahnya.
do $$
declare t text;
begin
 foreach t in array array['students','announcements','tasks','schedule','attendance','gallery','fund'] loop
  execute format('create policy "public read %1$s" on public.%1$I for select to anon, authenticated using (true)',t);
  execute format('create policy "admin insert %1$s" on public.%1$I for insert to authenticated with check (public.is_xi8_admin())',t);
  execute format('create policy "admin update %1$s" on public.%1$I for update to authenticated using (public.is_xi8_admin()) with check (public.is_xi8_admin())',t);
  execute format('create policy "admin delete %1$s" on public.%1$I for delete to authenticated using (public.is_xi8_admin())',t);
 end loop;
end $$;
create policy "public read aspirations" on public.aspirations for select to anon,authenticated using (true);
create policy "anyone submit aspiration" on public.aspirations for insert to anon,authenticated with check (true);
create policy "admin update aspirations" on public.aspirations for update to authenticated using (public.is_xi8_admin()) with check (public.is_xi8_admin());
create policy "admin delete aspirations" on public.aspirations for delete to authenticated using (public.is_xi8_admin());
